#!/usr/bin/env python3
"""Enforce the repository-root and generated-output policy from ADR 0003.

Run from any working directory with:
    python3 tools/repository/check_root_policy.py

The current repository is in a staged migration. Transitional root entries are
explicitly listed with their owning issue; they are warnings, not permanent
allowlist entries. New root entries and new root dependency manifests fail.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import PurePosixPath
from typing import Iterable

ALLOWED_ROOT_FILES = {
    ".editorconfig",
    ".gitattributes",
    ".gitignore",
    "CITATION.cff",
    "README.md",
    "CONTRIBUTING.md",
    "CODE_OF_CONDUCT.md",
    "SECURITY.md",
    "LICENSE",
}

TRANSITIONAL_ROOT_FILES = {
    "package.json": "#367 — move the npm workspace to npm/",
    "package-lock.json": "#265/#367 — generate with npm, then move the workspace to npm/",
    "requirements-dev.txt": "#365/#369 — move repository Python tooling dependencies under tools/repository/",
}

ALLOWED_ROOT_DIRECTORIES = {
    ".github",
    "docs",
    "contracts",
    "fixtures",
    "rust",
    "npm",
    "r",
    "python",
    "packaging",
    "tools",
}

TRANSITIONAL_ROOT_DIRECTORIES = {
    ".changeset": "#367 — move Changesets configuration under npm/",
    "benchmarks": "#364 — split cross-runtime orchestration and runtime-owned benchmarks",
    "bindings": "#366/#367 — split Rust binding crates from npm package content",
    "crates": "#366 — move the shared Rust crate under rust/",
    "experiments": "#364 — retain as a documented cross-runtime exception or approve another home",
    "implementations": "#368 — move the R package under r/corrplotng/",
    "packages": "#367 — move npm workspace packages under npm/packages/",
    "prototypes": "#366/#369/#370 — split Rust, Python reference code, contracts and fixtures",
    "scripts": "#365 — move repo-wide orchestration to tools/repository/ and R tools to r/",
    "tests": "#364/#370 — split canonical fixtures from repository/runtime-specific tests",
}

FORBIDDEN_ROOT_MANIFESTS = {
    "Cargo.toml",
    "Cargo.lock",
    "pyproject.toml",
    "Pipfile",
    "Pipfile.lock",
    "poetry.lock",
    "uv.lock",
    "DESCRIPTION",
    "NAMESPACE",
    "renv.lock",
}

GENERATED_DIRECTORY_NAMES = {
    "node_modules",
    "target",
    ".venv",
    "venv",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    ".Rproj.user",
    "Rlibs",
}

GENERATED_DIRECTORY_SEQUENCES = {
    ("renv", "library"),
    ("renv", "staging"),
}

GENERATED_PATH_SUFFIXES = {".pyc", ".pyo", ".node"}
GENERATED_PATH_PREFIXES = (
    "bindings/wasm/pkg/",
    "npm/packages/wasm/pkg/",
    "prototypes/rust-rextendr/.ci-r-package/",
)


def validate_paths(paths: Iterable[str]) -> tuple[list[str], list[str]]:
    """Return (errors, transitional warnings) for tracked repository paths."""
    normalized = sorted({PurePosixPath(path).as_posix().removeprefix("./").lstrip("/") for path in paths if path})
    errors: list[str] = []
    warnings: list[str] = []
    root_entries: set[str] = set()

    for path in normalized:
        parts = PurePosixPath(path).parts
        if not parts:
            continue
        root_entries.add(parts[0])

        if any(part in GENERATED_DIRECTORY_NAMES or part.endswith(".Rcheck") for part in parts):
            errors.append(
                f"{path}: generated dependency/build directory is tracked; "
                "remove it from Git and keep it ignored"
            )
        if any(
            tuple(parts[index:index + len(sequence)]) == sequence
            for sequence in GENERATED_DIRECTORY_SEQUENCES
            for index in range(max(0, len(parts) - len(sequence) + 1))
        ):
            errors.append(
                f"{path}: generated local R library/staging directory is tracked; "
                "remove it from Git and keep it ignored"
            )
        if PurePosixPath(path).suffix in GENERATED_PATH_SUFFIXES:
            errors.append(f"{path}: generated bytecode/native addon is tracked")
        if any(path.startswith(prefix) for prefix in GENERATED_PATH_PREFIXES):
            errors.append(f"{path}: generated package/build output is tracked")

        if len(parts) == 1:
            name = parts[0]
            if name in FORBIDDEN_ROOT_MANIFESTS:
                errors.append(
                    f"{path}: ecosystem manifest/lockfile is not allowed at repository root; "
                    "move it to its owning ecosystem directory"
                )
            elif name in TRANSITIONAL_ROOT_FILES:
                warnings.append(f"{path}: transitional root file — {TRANSITIONAL_ROOT_FILES[name]}")
            elif name not in ALLOWED_ROOT_FILES and name not in FORBIDDEN_ROOT_MANIFESTS:
                # The root-entry check below reports this once, with the same
                # guidance as for an unexpected top-level directory.
                pass

    for name in sorted(root_entries):
        if name in ALLOWED_ROOT_FILES or name in ALLOWED_ROOT_DIRECTORIES:
            continue
        if name in TRANSITIONAL_ROOT_FILES:
            continue
        if name in TRANSITIONAL_ROOT_DIRECTORIES:
            warnings.append(f"{name}/: transitional root directory — {TRANSITIONAL_ROOT_DIRECTORIES[name]}")
            continue
        if name in FORBIDDEN_ROOT_MANIFESTS:
            continue
        # package.json and requirements-dev.txt are transitional files above;
        # all other unknown root entries require an explicit policy decision.
        if name in TRANSITIONAL_ROOT_FILES:
            continue
        errors.append(
            f"{name}: unreviewed repository-root entry; add it to the documented "
            "root allowlist or place it under its owning project"
        )

    return sorted(set(errors)), sorted(set(warnings))


def main() -> int:
    try:
        result = subprocess.run(
            ["git", "ls-files", "-z"],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
    except (OSError, subprocess.CalledProcessError) as error:
        print(f"ROOT POLICY ERROR: cannot enumerate tracked files with git ls-files: {error}", file=sys.stderr)
        return 2

    paths = [item.decode("utf-8", errors="surrogateescape") for item in result.stdout.split(b"\0") if item]
    errors, warnings = validate_paths(paths)

    for warning in warnings:
        print(f"ROOT POLICY TRANSITION: {warning}")
    for error in errors:
        print(f"ROOT POLICY ERROR: {error}", file=sys.stderr)

    if errors:
        print(f"Root policy failed with {len(errors)} error(s).", file=sys.stderr)
        return 1

    print(
        f"Root policy passed: {len(paths)} tracked paths checked; "
        f"{len(warnings)} documented transitional root entries remain."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
